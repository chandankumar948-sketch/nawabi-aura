/**
 * Display order: products carrying a `ranking` from the master sheet come
 * first, ascending; everything unranked keeps its catalog order behind them.
 */
export const sortedProducts: Product[] = [...products].sort((a, b) => {
  const ra = a.ranking ?? Number.POSITIVE_INFINITY;
  const rb = b.ranking ?? Number.POSITIVE_INFINITY;
  if (ra !== rb) return ra - rb;
  return Number(a.id) - Number(b.id);
});

